def process(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    idx = text.find(MARKER)
    if idx < 0:
        return False
    head = text[: idx + len(MARKER)]
    body = text[idx + len(MARKER) :].lstrip("\n\r")
    orig = body
    for old, new in REPLACEMENTS:
        body = body.replace(old, new)
    if body == orig:
        changed = False
    else:
        changed = True
    full = head + "\n\n" + body
    if NOTE_APPEND not in full and "备注:" in full.split(MARKER, 1)[0]:
        full = re.sub(
            r"(备注:[^\n]+)",
            lambda m: m.group(1) if NOTE_APPEND in m.group(1) else m.group(1) + "；" + NOTE_APPEND,
            full,
            count=1,
        )
    path.write_text(full, encoding="utf-8")
    return changed


